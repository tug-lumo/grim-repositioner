"""Pack the scale-reference models into assets/ref/models.js so the app can load them from a
double-clicked index.html (browsers refuse to fetch files over file://, but a <script> is fine).

    python scripts/embed-models.py

Sources (copied from Mock & Roll's assets, both in metres, Y up):
    assets/ref/car.glb     <- LumoSTAGER/assets/vehicles/muscle-car.glb     (nose to -X, 15' 8.4" long)
    assets/ref/person.glb  <- LumoSTAGER/assets/people/person-08.glb        (grey low-poly man, standing)
"""
import base64
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "ref")
out = ["// Generated by scripts/embed-models.py. Do not edit.", "window.GRIM_REF_MODELS = {"]
for name in ("car", "person"):
    b64 = base64.b64encode(open(os.path.join(ROOT, name + ".glb"), "rb").read()).decode("ascii")
    out.append('  %s: "%s",' % (name, b64))
out.append("};")
open(os.path.join(ROOT, "models.js"), "w", newline="\n").write("\n".join(out) + "\n")
print("Wrote assets/ref/models.js")
